export type LanguageCode = string;

export function translate(language: LanguageCode, key: keyof typeof messages.vi, values?: Record<string, string | number>): string {
  const catalog = language.toLowerCase().startsWith("vi") ? messages.vi : messages.en;
  let message: string = catalog[key] ?? messages.en[key];
  for (const [name, value] of Object.entries(values ?? {})) {
    message = message.replace(`{${name}}`, String(value));
  }
  return message;
}

export function languageLabel(language: LanguageCode): string {
  if (language === "vi") return translate("vi", "vietnamese");
  if (language === "en") return translate("en", "english");
  return language.toUpperCase();
}

export function categoryLabel(category: string, language: LanguageCode): string {
  const labels: Record<string, { vi: string; en: string }> = {
    historical: { vi: "Lịch sử", en: "Historical" },
    religious: { vi: "Tôn giáo", en: "Religious" },
    market: { vi: "Chợ", en: "Market" },
    museum: { vi: "Bảo tàng", en: "Museum" },
    "public-space": { vi: "Không gian công cộng", en: "Public space" },
    nature: { vi: "Thiên nhiên", en: "Nature" },
    education: { vi: "Giáo dục", en: "Education" },
    cultural: { vi: "Văn hóa", en: "Culture" },
  };
  const selected = labels[category.toLowerCase()];
  if (!selected) return category.split("-").join(" ");
  return language.toLowerCase().startsWith("vi") ? selected.vi : selected.en;
}
